// Writes Name.module.css.d.ts beside every CSS module, naming exactly the classes it defines, so `styles.tabbar` is a
// string and a misspelt class is a compile error (strict TypeScript would otherwise type every class as maybe missing).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

function* modules(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* modules(path);
    else if (entry.name.endsWith(".module.css")) yield path;
  }
}

for (const file of modules("src")) {
  const css = readFileSync(file, "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
  const names = [...new Set([...css.matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)].map((m) => m[1]))].sort();
  const fields = names.map((name) => `  readonly ${JSON.stringify(name)}: string;`).join("\n");
  writeFileSync(
    `${file}.d.ts`,
    `// Generated by scripts/css-module-types.mjs: do not edit.\ndeclare const styles: {\n${fields}\n};\nexport default styles;\n`,
  );
}
